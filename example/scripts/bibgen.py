def find_repo_root() -> Path:
    """Resolve the manuscript containing this script."""
    return Path(__file__).resolve().parent.parent


def parse_bib_entries(content: str) -> list[tuple[str, str, str]]:
    """Parse BibTeX blocks from text into a list of (entry_type, citekey, full_text).

    Handles nested braces and escaped characters robustly.
    """
    entries = []
    # Match starting with @type{citekey,
    entry_pattern = re.compile(r"@([a-zA-Z]+)\s*\{\s*([^,\s]+)\s*,", re.MULTILINE)

    pos = 0
    length = len(content)

    while pos < length:
        match = entry_pattern.search(content, pos)
        if not match:
            break

        start_idx = match.start()
        entry_type = match.group(1).lower()
        citekey = match.group(2).strip()

        # Track brace depth from the opening brace after entry_type
        brace_start = match.end() - 1
        brace_depth = 1
        curr = brace_start + 1
        in_quotes = False

        while curr < length and brace_depth > 0:
            char = content[curr]
            prev = content[curr - 1] if curr > 0 else ""

            if char == '"' and prev != "\\":
                in_quotes = not in_quotes
            elif not in_quotes:
                if char == "{" and prev != "\\":
                    brace_depth += 1
                elif char == "}" and prev != "\\":
                    brace_depth -= 1

            curr += 1

        if brace_depth == 0:
            full_block = content[start_idx:curr].strip()
            entries.append((entry_type, citekey, full_block))
            pos = curr
        else:
            pos = match.end()

    return entries


def aggregate_hub(repo_root: Path) -> int:
    """Aggregate all references/bib/*.bib entries into references/references.bib."""
    entries_dir = repo_root / "references" / "bib"
    out_file = repo_root / "references" / "references.bib"

    if not entries_dir.exists():
        print(f"Error: reference directory not found at {entries_dir}", file=sys.stderr)
        return 1

    entries_by_key: dict[str, str] = {}
    for path in sorted(entries_dir.glob("*.bib")):
        parsed = parse_bib_entries(path.read_text(encoding="utf-8"))
        if not parsed:
            raise ValueError(f"No BibTeX record in {path}")
        for _, key, block in parsed:
            if key in entries_by_key and entries_by_key[key] != block:
                raise ValueError(f"Conflicting duplicate citekey: {key}")
            entries_by_key[key] = block
    if not entries_by_key:
        raise ValueError("No curated entries found in references/bib/")
    controls = sum(
        parse_bib_entries(block)[0][0] == "control" for block in entries_by_key.values()
    )
    header = (
        "% Consolidated bibliography; generated by scripts/bibgen.py.\n"
        "% Edit individual records under references/bib/.\n"
        f"% Total curated references: {len(entries_by_key) - controls}; controls: {controls}\n\n"
    )
    content = (
        header
        + "\n\n".join(
            entries_by_key[key] for key in sorted(entries_by_key, key=str.lower)
        )
        + "\n"
    )
    temporary = out_file.with_suffix(".bib.tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(out_file)
    print(
        f"Aggregated {len(entries_by_key) - controls} references and {controls} controls into references/references.bib"
    )
    return 0


def split_monolith(repo_root: Path, source_file: Path | None = None) -> int:
    """Split monolithic references.bib into atomic references/bib/<citekey>.bib files."""
    entries_dir = repo_root / "references" / "bib"
    src = source_file or (repo_root / "references" / "references.bib")

    if not src.exists():
        print(f"Error: Source file {src} does not exist.", file=sys.stderr)
        return 1

    content = src.read_text(encoding="utf-8")
    entries = parse_bib_entries(content)

    print(
        f"Splitting {len(entries)} entries from {src.name} into references/bib/ reference folder..."
    )
    created = 0

    for etype, key, block in entries:
        target_dir = entries_dir
        target_dir.mkdir(parents=True, exist_ok=True)

        target_file = target_dir / f"{key}.bib"
        clean_block = block.strip() + "\n"
        target_file.write_text(clean_block, encoding="utf-8")
        created += 1

    print(
        f"=== [✓] Successfully split {created} references across references/bib/ folders ==="
    )
    return 0


def fetch_doi_crossref(doi: str) -> str:
    """Query CrossRef API via doi.org to retrieve official BibTeX entry."""
    # Clean DOI string
    clean_doi = re.sub(r"^https?://(dx\.)?doi\.org/", "", doi.strip())
    clean_doi = re.sub(r"^doi:\s*", "", clean_doi, flags=re.IGNORECASE)
    clean_doi = clean_doi.strip("()[]{}<>\"' ")

    url = f"https://doi.org/{clean_doi}"
    headers = {
        "Accept": "application/x-bibtex",
        "User-Agent": "Aspyrus-BibGen/1.0",
    }

    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=10) as resp:
        charset = resp.headers.get_content_charset() or "utf-8"
        raw_bib = resp.read().decode(charset)

    return raw_bib.strip()


def format_bib_record(kind: str, key: str, fields: dict[str, str]) -> str:
    """Format literal fields without changing their values or nested LaTeX braces."""
    preferred = "author title journal booktitle publisher year volume number pages eid doi url".split()
    names = [name for name in preferred if name in fields]
    names += sorted(set(fields) - set(names))
    return (
        f"@{kind}{{{key},\n"
        + ",\n".join(f"  {name:<9} = {{{fields[name]}}}" for name in names)
        + "\n}"
    )


def normalize_citekey(raw_bib: str) -> tuple[str, str]:
    """Name new imports FirstAuthorYearShortTopic; preserve established keys elsewhere."""
    parsed = parse_bib_entries(raw_bib)
    if len(parsed) != 1:
        raise ValueError("Expected exactly one complete DOI record")
    kind, _, block = parsed[0]
    fields = bib_fields(block)
    author = fields.get("author", "").split(" and ")[0]
    family = (
        author.split(",")[0]
        if "," in author
        else author.split()[-1]
        if author.split()
        else ""
    )
    family = re.sub(r"[^A-Za-z]", "", family)
    year = fields.get("year", "")
    stop = {
        "a",
        "an",
        "the",
        "of",
        "and",
        "for",
        "in",
        "on",
        "to",
        "is",
        "are",
        "by",
        "with",
    }
    words = [
        word
        for word in re.findall(r"[A-Za-z0-9]+", fields.get("title", ""))
        if word.lower() not in stop
    ][:3]
    if not family or not re.fullmatch(r"\d{4}", year) or not words:
        raise ValueError("Author, year and title required for a new citation key")
    key = family + year + "".join(word[0].upper() + word[1:] for word in words)
    return key, format_bib_record(kind, key, fields)


def canonical_doi(value: str) -> str:
    """Normalize identifiers for matching without changing citation keys."""
    value = re.sub(r"^https?://(?:dx\.)?doi\.org/", "", value.strip(), flags=re.I)
    value = re.sub(r"^doi:\s*", "", value, flags=re.I).strip().lower()
    if not re.fullmatch(r"10\.\d{4,9}/\S+", value):
        raise ValueError(f"Invalid DOI: {value}")
    return value


CSV_COLUMNS = "doi citekey title authors publication_type publication year volume issue pages_or_article_id fields_checked missing_fields discrepancies action_taken review_reason source_urls checked_at comments status".split()


def read_reference_state(repo_root: Path) -> dict:
    """Read the consolidated ledger; retain exact legacy content for migration."""
    folder = repo_root / "references"
    current = folder / "references.json"
    state = json.loads(current.read_text()) if current.exists() else {}
    legacy = state.setdefault("legacy", {})
    for name in (
        "verification.json",
        "verification_reviews.json",
        "verification_notes.md",
    ):
        path = folder / name
        if path.exists() and name not in legacy:
            legacy[name] = {
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "content": path.read_text(),
            }
            if name == "verification.json" and not current.exists():
                state.update(json.loads(path.read_text()))
            if name == "verification_reviews.json":
                state.setdefault("reviews", {}).update(
                    json.loads(path.read_text()).get("records", {})
                )
    return state


def save_reference_state(repo_root: Path, state: dict) -> None:
    """CSV is an inspection projection of the JSON ledger, never a decision input."""
    folder = repo_root / "references"
    folder.mkdir(parents=True, exist_ok=True)
    destination = folder / "references.json"
    temporary = destination.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n")
    temporary.replace(destination)
    rows = []
    seen = set()
    for key, record in state.get("records", {}).items():
        fields = record.get("fields", {})
        doi = fields.get("doi", "")
        seen.add(doi.lower())
        flags = record.get("flags", [])
        status = (
            "READY"
            if not flags
            and record.get("status") in {"metadata_match", "reviewed_exception"}
            and record.get("evidence")
            else "CHECK"
        )
        issues = []
        if any("lookup failed" in flag for flag in flags):
            issues.append("Retrieval failed; check DOI/network and retry")
        if any(flag.startswith("missing ") for flag in flags):
            issues.append(
                "Missing bibliographic information; supply authoritative evidence"
            )
        if any("author" in flag for flag in flags):
            issues.append("Authors differ; check publisher author list")
        differing = [
            flag.split(": ", 1)[1]
            for flag in flags
            if flag.startswith("metadata differs: ")
        ]
        if differing:
            issues.append(
                "Metadata differs ("
                + ", ".join(differing)
                + "); inspect discrepancies and publisher citation"
            )
        if any(flag.startswith("unverified") for flag in flags):
            issues.append(
                "No current metadata evidence; refresh or supply a reviewed source"
            )
        comments = (
            "; ".join(issues)
            if issues
            else "Inspect flagged fields and source evidence"
            if status == "CHECK"
            else "Metadata checks resolved; rendering and claim support require separate review"
        )
        review = record.get("review", {})
        annotation = state.get("annotations", {}).get(key, {})
        evidence = record.get("evidence", {})
        rows.append(
            dict(
                zip(
                    CSV_COLUMNS,
                    [
                        doi,
                        key,
                        fields.get("title", ""),
                        fields.get("author", ""),
                        record.get("entry_type", ""),
                        fields.get("journal", fields.get("booktitle", "")),
                        fields.get("year", ""),
                        fields.get("volume", ""),
                        fields.get("number", ""),
                        fields.get("pages", fields.get("eid", "")),
                        "; ".join(record.get("fields_checked", [])),
                        "; ".join(
                            flag for flag in flags if flag.startswith("missing ")
                        ),
                        "; ".join(record.get("discrepancies", flags)),
                        annotation.get(
                            "action",
                            state.get("imports", {})
                            .get(doi.lower(), {})
                            .get("action", "unchanged"),
                        ),
                        review.get("reason", annotation.get("reason", "")),
                        "; ".join(
                            dict.fromkeys(
                                [evidence["source_url"]]
                                if evidence.get("source_url")
                                else []
                            )
                        )
                        + (
                            "; " + "; ".join(review.get("source_urls", []))
                            if review.get("source_urls")
                            else ""
                        ),
                        state.get("generated_at", ""),
                        comments,
                        status,
                    ],
                )
            )
        )
    for doi, event in state.get("imports", {}).items():
        if doi not in seen and event.get("action") == "failed":
            rows.append(
                {
                    "doi": doi,
                    "action_taken": "failed",
                    "status": "CHECK",
                    "comments": event["error"]
                    + "; retry retrieval or inspect identifier",
                    "checked_at": event["at"],
                }
            )
    output = folder / "references.csv"
    temporary = output.with_suffix(".csv.tmp")
    with temporary.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=CSV_COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    temporary.replace(output)


def prepare_references(repo_root: Path) -> int:
    """Explicit article handoff and network preparation; builds never call this."""
    config = json.loads((repo_root / ".aspyrus.json").read_text())
    source_name = config.get("references", {}).get("doi_source")
    if not source_name:
        raise ValueError("Configure references.doi_source in .aspyrus.json first")
    source = (repo_root / source_name).resolve()
    dois = list(
        dict.fromkeys(
            canonical_doi(line)
            for line in source.read_text().splitlines()
            if line.strip() and not line.lstrip().startswith("#")
        )
    )
    destination = repo_root / "references/dois.txt"
    existing = (
        list(
            dict.fromkeys(
                canonical_doi(line)
                for line in destination.read_text().splitlines()
                if line.strip() and not line.lstrip().startswith("#")
            )
        )
        if destination.exists()
        else []
    )
    added = [doi for doi in dois if doi not in existing]
    omitted = [doi for doi in existing if doi not in dois]
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".txt.tmp")
    temporary.write_text(
        "\n".join(existing + added) + ("\n" if existing or added else "")
    )
    temporary.replace(destination)
    state = read_reference_state(repo_root)
    state["handoff"] = {
        "source": str(source),
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "added": added,
        "omitted_retained": omitted,
        "at": datetime.now(timezone.utc).isoformat(),
    }
    save_reference_state(repo_root, state)
    print(
        f"DOI handoff: {len(added)} added, {len(omitted)} omitted identifiers retained"
    )
    result = ingest_doi_list(repo_root, destination)
    if (repo_root / "references/references.bib").exists():
        result = max(
            result,
            audit_references(repo_root, refresh=True, all_references=True),
            check_citations(repo_root),
        )
    print(
        "Inspect references/references.csv: filter the final status column for CHECK, then read comments."
    )
    return result


def ingest_doi_list(repo_root: Path, source: Path) -> int:
    """Explicitly retrieve missing DOIs; never overwrite existing records."""
    dois = list(
        dict.fromkeys(
            canonical_doi(line)
            for line in source.read_text().splitlines()
            if line.strip() and not line.lstrip().startswith("#")
        )
    )
    entries_dir = repo_root / "references" / "bib"
    existing = set()
    for path in entries_dir.glob("*.bib"):
        for _, _, block in parse_bib_entries(path.read_text()):
            fields = bib_fields(block)
            if fields.get("doi"):
                existing.add(canonical_doi(fields["doi"]))
    state = read_reference_state(repo_root)
    events = state.setdefault("imports", {})
    failures = 0
    for doi in dois:
        if doi in existing:
            events.setdefault(
                doi,
                {"action": "retained", "at": datetime.now(timezone.utc).isoformat()},
            )
            print(f"Already present: {doi}")
            continue
        try:
            time.sleep(1)
            key, block = normalize_citekey(fetch_doi_crossref(doi))
            kind, _, _ = parse_bib_entries(block)[0]
            fields = bib_fields(block)
            if canonical_doi(fields.get("doi", "")) != doi:
                raise ValueError("Returned DOI does not match requested DOI")
            # Publisher feeds sometimes use nonstandard Sept; store a literal month.
            if fields.get("month"):
                block = re.sub(
                    r"(\bmonth\s*=\s*)(?:jan|feb|mar|apr|may|jun|jul|aug|sept?|oct|nov|dec)(?=\s*[,}])",
                    lambda match: match.group(1) + "{" + fields["month"] + "}",
                    block,
                    flags=re.I,
                )
            flags = metadata_flags(kind, fields)
            if flags:
                raise ValueError("; ".join(flags))
            entries_dir.mkdir(parents=True, exist_ok=True)
            destination = entries_dir / f"{key}.bib"
            with destination.open("x", encoding="utf-8") as stream:
                stream.write(block + "\n")
            existing.add(doi)
            events[doi] = {
                "action": "retrieved",
                "at": datetime.now(timezone.utc).isoformat(),
                "citekey": key,
            }
            print(f"Added {doi}: {key} (metadata audit still required)")
        except (OSError, ValueError) as exc:
            failures += 1
            events[doi] = {
                "action": "failed",
                "at": datetime.now(timezone.utc).isoformat(),
                "error": str(exc),
            }
            print(f"Needs review: {doi}: {exc}", file=sys.stderr)
    save_reference_state(repo_root, state)
    if any(entries_dir.glob("*.bib")):
        aggregate_hub(repo_root)
    return 1 if failures else 0


def handle_doi_ingestion(repo_root: Path, doi: str) -> int:
    """Use the same protected import path for single and list requests."""
    import tempfile

    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "dois.txt"
        source.write_text(doi + "\n", encoding="utf-8")
        return ingest_doi_list(repo_root, source)


def check_citations(repo_root: Path) -> int:
    """Verify citekeys between main.tex and references.bib."""
    main_tex = repo_root / "main" / "main.tex"
    ref_bib = repo_root / "references" / "references.bib"

    if not main_tex.exists() or not ref_bib.exists():
        print("Error: main.tex or references.bib missing.", file=sys.stderr)
        return 1

    tex_content = "\n".join(
        p.read_text(encoding="utf-8")
        for p in [main_tex, repo_root / "supplementary" / "supplementary.tex"]
        if p.exists()
    )
    # Strip comments and verbatim inline blocks before scanning citations
    cleaned = re.sub(r"(?<!\\)%.*$", "", tex_content, flags=re.MULTILINE)
    cleaned = re.sub(r"\\verb([|#+*~]).*?\1", "", cleaned)

    bib_content = ref_bib.read_text(encoding="utf-8")

    cited_keys = set()
    for match in re.finditer(r"\\(cite|revref|nocite)\{([^}]+)\}", cleaned):
        for k in match.group(2).split(","):
            k = k.strip()
            if k and not k.startswith("#") and k != "...":
                cited_keys.add(k)

    available_keys = {key for _, key, _ in parse_bib_entries(bib_content)}

    control_keys = {
        key for kind, key, _ in parse_bib_entries(bib_content) if kind == "control"
    }
    if "*" in cited_keys:
        cited_keys = (cited_keys - {"*"}) | (available_keys - control_keys)
    missing_keys = cited_keys - available_keys
    unused_keys = available_keys - cited_keys - control_keys

    print("--- Citation Audit: main and supplementary ---")
    print(f"Unique cited keys in authored documents: {len(cited_keys)}")
    print(
        f"Available references: {len(available_keys - control_keys)}; bibliography controls: {len(control_keys)}"
    )

    if missing_keys:
        print(
            f"\n[!] WARNING: {len(missing_keys)} keys cited in authored documents are MISSING from references.bib:"
        )
        for k in sorted(missing_keys):
            print(f"    - {k}")
    else:
        print(
            "\n[✓] All keys cited in authored documents are present in references.bib."
        )

    print(
        f"\nInfo: {len(unused_keys)} curated references in references.bib are not cited in authored documents."
    )
    return 0 if not missing_keys else 1


def bib_fields(block: str) -> dict[str, str]:
    """Read literal BibTeX fields, preserving nested braces; reject expressions."""
    fields = {}
    pos = block.index(",") + 1
    while True:
        match = re.match(r"\s*,?\s*([\w-]+)\s*=\s*", block[pos:])
        if not match:
            if block[pos:].strip(" \t\r\n,}"):
                raise ValueError("Unsupported BibTeX field syntax")
            return fields
        name = match.group(1).lower()
        pos += match.end()
        start = pos
        if block[pos] in '{"':
            opening = block[pos]
            closing = "}" if opening == "{" else '"'
            depth = 1
            pos += 1
            start = pos
            while pos < len(block) and depth:
                char = block[pos]
                if char == "\\":
                    pos += 2
                    continue
                if opening == "{" and char == "{":
                    depth += 1
                if char == closing:
                    depth -= 1
                pos += 1
            if depth:
                raise ValueError("Unclosed BibTeX field")
            value = block[start : pos - 1]
        else:
            while pos < len(block) and block[pos] not in ",}":
                pos += 1
            value = block[start:pos].strip()
            if not value.isdigit():
                months = dict(
                    zip(
                        "jan feb mar apr may jun jul aug sep oct nov dec".split(),
                        "January February March April May June July August September October November December".split(),
                    )
                )
                if name == "month" and (
                    value.lower() in months or value.lower() == "sept"
                ):
                    value = months["sep" if value.lower() == "sept" else value.lower()]
                else:
                    raise ValueError("BibTeX string macros require manual review")
        if name in fields:
            raise ValueError(f"Duplicate field: {name}")
        fields[name] = value.strip()
        if pos < len(block) and block[pos:].lstrip().startswith("#"):
            raise ValueError("BibTeX concatenation requires manual review")


def metadata_flags(kind: str, fields: dict[str, str]) -> list[str]:
    required = {
        "article": ("author", "title", "journal", "year"),
        "inbook": ("title", "booktitle", "publisher", "year"),
        "incollection": ("title", "booktitle", "publisher", "year"),
        "book": ("title", "publisher", "year"),
        "inproceedings": ("author", "title", "booktitle", "year"),
    }
    if kind not in required:
        return [f"manual review: unsupported publication type {kind}"]
    flags = [f"missing {name}" for name in required[kind] if not fields.get(name)]
    if not fields.get("author") and not fields.get("editor"):
        flags.append("missing author or editor")
    if kind in {"article", "inbook", "incollection", "inproceedings"}:
        if not fields.get("pages") and not fields.get("eid"):
            flags.append("missing pages or article identifier; review publication")
    if kind == "article" and not fields.get("volume"):
        flags.append("missing volume; review online-first/unvolume publication")
    if not fields.get("doi") and not fields.get("url"):
        flags.append("missing DOI or source URL; manual evidence required")
    return flags


def normalized_metadata(value: str) -> str:
    """Conservative comparison: punctuation/case differ, substantive text must match."""
    value = html.unescape(re.sub(r"<[^>]*>", "", value))
    value = re.sub(r"\\[\"'`^~=.uvHckbdtr]\s*\{?([A-Za-z])\}?", r"\1", value)
    value = unicodedata.normalize("NFKD", value)
    return "".join(c for c in value.casefold() if c.isalnum())


def metadata_digest(message: dict) -> str:
    return hashlib.sha256(
        json.dumps(message, sort_keys=True, ensure_ascii=False).encode()
    ).hexdigest()


def apply_reference_review(record: dict, review: dict) -> None:
    """Keep discrepancies visible; resolve only evidence-bound, explicitly reviewed flags."""
    record["detected_flags"] = list(record["flags"])
    evidence = record.get("evidence", {})
    valid = (
        review.get("record_sha256") == record["record_sha256"]
        and evidence.get("message") is not None
        and review.get("metadata_sha256") == metadata_digest(evidence["message"])
        and bool(review.get("reason"))
        and bool(review.get("source_urls"))
        and bool(review.get("reviewed_at"))
    )
    if review:
        record["review_valid"] = valid
    if valid:
        approved = review.get("accepted_flags", [])
        record["flags"] = [flag for flag in record["flags"] if flag not in approved]
        record["review"] = review
    record["status"] = (
        "needs_review"
        if record["flags"]
        else "reviewed_exception"
        if valid and record["detected_flags"]
        else "metadata_match"
    )


def audit_references(
    repo_root: Path, refresh: bool = False, all_references: bool = False
) -> int:
    """Audit cited/nocited records; network access is explicit, never repair metadata."""
    report_path = repo_root / "references" / "references.json"
    previous = read_reference_state(repo_root)
    prior = {**previous.get("cached_records", {}), **previous.get("records", {})}
    reviews = previous.get("reviews", {})
    tex_paths = [repo_root / name / f"{name}.tex" for name in ("main", "supplementary")]
    tex = "\n".join(p.read_text() for p in tex_paths if p.exists())
    tex = re.sub(r"(?<!\\)%.*$", "", tex, flags=re.MULTILINE)
    keys = {
        k.strip()
        for m in re.finditer(r"\\(?:cite|revref|nocite)\{([^}]+)\}", tex)
        for k in m.group(1).split(",")
        if k.strip() and not k.strip().startswith("#") and k.strip() != "..."
    }
    entries = parse_bib_entries((repo_root / "references/references.bib").read_text())
    if all_references or "*" in keys:
        keys = {key for kind, key, block in entries if kind != "control"}
    records = {}
    for kind, key, block in entries:
        if key not in keys or kind == "control":
            continue
        digest = hashlib.sha256(block.encode()).hexdigest()
        record = {"record_sha256": digest, "entry_type": kind, "flags": []}
        records[key] = record
        try:
            fields = bib_fields(block)
        except ValueError as exc:
            record["flags"].append(str(exc))
            record["status"] = "needs_review"
            continue
        record["fields"] = fields
        record["fields_checked"] = ["required-field presence"]
        record["discrepancies"] = []
        record["flags"] = metadata_flags(kind, fields)
        doi = re.sub(
            r"^https?://(?:dx\.)?doi\.org/", "", fields.get("doi", ""), flags=re.I
        ).strip()
        cached = prior.get(key, {})
        if refresh and doi:
            url = "https://api.crossref.org/works/" + urllib.parse.quote(doi, safe="")
            try:
                req = urllib.request.Request(
                    url, headers={"User-Agent": "BibGen-reference-audit/1.0"}
                )
                time.sleep(1)  # Keep explicit bulk requests below one per second.
                for attempt in range(3):
                    try:
                        with urllib.request.urlopen(req, timeout=15) as response:
                            message = json.load(response)["message"]
                        break
                    except urllib.error.HTTPError as exc:
                        if exc.code != 429 or attempt == 2:
                            raise
                        time.sleep(5 * (attempt + 1))
                record["evidence"] = {
                    "source_url": url,
                    "retrieved_at": datetime.now(timezone.utc).isoformat(),
                    "message": {
                        name: message[name]
                        for name in (
                            "DOI",
                            "title",
                            "container-title",
                            "author",
                            "volume",
                            "issue",
                            "page",
                            "article-number",
                            "published",
                            "issued",
                            "type",
                            "publisher",
                            "ISBN",
                            "ISSN",
                        )
                        if name in message
                    },
                }
            except (urllib.error.URLError, TimeoutError, ValueError, KeyError) as exc:
                record["flags"].append(f"metadata lookup failed: {exc}")
                if cached.get("evidence"):
                    record["previous_evidence"] = cached["evidence"]
        elif cached.get("record_sha256") == digest and cached.get("evidence"):
            record["evidence"] = cached["evidence"]
        else:
            record["flags"].append("unverified or changed record; refresh metadata")
        evidence = record.get("evidence")
        if evidence:
            remote = evidence["message"]
            if normalized_metadata(remote.get("DOI", "")) != normalized_metadata(doi):
                record["flags"].append("DOI identity mismatch")
            expected_type = {
                "article": "journal-article",
                "inbook": "book-chapter",
                "incollection": "book-chapter",
                "inproceedings": "proceedings-article",
                "book": "book",
            }.get(kind)
            if remote.get("type") != expected_type:
                record["flags"].append("publication type requires review")
            comparisons = {
                "title": (remote.get("title") or [""])[0],
                "volume": remote.get("volume", ""),
                "number": remote.get("issue", ""),
                "pages": remote.get("page", remote.get("article-number", "")),
            }
            if kind == "book":
                comparisons["publisher"] = remote.get("publisher", "")
            if kind == "article":
                comparisons["journal"] = (remote.get("container-title") or [""])[0]
            elif kind == "inproceedings":
                comparisons["booktitle"] = (remote.get("container-title") or [""])[0]
            elif kind in {"inbook", "incollection"}:
                record["flags"].append(
                    "chapter container/series/editors require publisher review"
                )
            dates = remote.get("published", remote.get("issued", {})).get(
                "date-parts", [[]]
            )
            comparisons["year"] = str(dates[0][0]) if dates and dates[0] else ""
            record["fields_checked"] += ["doi", "publication_type", "authors"] + list(
                comparisons
            )
            for name, expected in comparisons.items():
                actual = fields.get(
                    name, fields.get("eid", "") if name == "pages" else ""
                )
                if actual or expected:
                    if not expected:
                        record["flags"].append(f"source lacks {name}; manual review")
                    elif normalized_metadata(actual) != normalized_metadata(
                        str(expected)
                    ):
                        record["flags"].append(f"metadata differs: {name}")
                        record["discrepancies"].append(
                            f"{name}: local={actual}; retrieved={expected}"
                        )
            authors = remote.get("author", [])
            local_authors = re.split(r"\s+and\s+", fields.get("author", ""))
            expected_authors = [
                f"{a.get('family', '')}, "
                + (f"{a['suffix']}, " if a.get("suffix") else "")
                + a.get("given", "")
                for a in authors
            ]
            # Keep suffix discrepancies separate from previously reviewed spelling flags.
            if len(local_authors) == len(authors):
                for local, remote_author in zip(local_authors, authors):
                    parts = [part.strip() for part in local.split(",")]
                    local_suffix = parts[1] if len(parts) == 3 else ""
                    if normalized_metadata(local_suffix) != normalized_metadata(
                        remote_author.get("suffix", "")
                    ):
                        record["flags"].append("author suffixes require review")
                        break
            if not authors or [normalized_metadata(a) for a in local_authors] != [
                normalized_metadata(a) for a in expected_authors
            ]:
                record["flags"].append("author list/order/spelling requires review")
                record["discrepancies"].append(
                    "authors: local="
                    + "; ".join(local_authors)
                    + "; retrieved="
                    + "; ".join(expected_authors)
                )
        apply_reference_review(record, reviews.get(key, {}))
    missing = sorted(keys - {key for _, key, _ in entries})
    report = {
        **previous,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "scope": "all library records"
        if all_references
        else "main and supplementary citations, including nocite",
        "source_sha256": {
            str(p.relative_to(repo_root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in tex_paths
            if p.exists()
        },
        "checker_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "missing_keys": missing,
        "records": records,
        "cached_records": {
            key: value for key, value in prior.items() if key not in records
        },
        "limitations": "Metadata matches are not publisher/manual verification, output completeness checks or claim-support verification. Missing fields and legitimate publication exceptions remain review flags; no automatic repairs.",
    }
    save_reference_state(repo_root, report)
    flagged = sum(bool(r["flags"]) for r in records.values())
    print(
        f"Reference audit: {len(records)} included records, {flagged} need review, {len(missing)} missing keys. Report: {report_path}"
    )
    return 1 if flagged or missing else 0


def render_tex_for_mode(
    repo_root: Path,
    mode: str,
    input_file: Path | None = None,
    output_file: Path | None = None,
) -> int:
    """Preprocess LaTeX source to render citations in chosen mode (numbers, dois, keys)."""
    src = input_file or (repo_root / "main" / "main.tex")
    dst = output_file or (repo_root / f"._tmp_{src.stem}_{mode}.tex")

    text = src.read_text(encoding="utf-8", errors="ignore")
    if mode == "numbers":
        dst.write_text(text, encoding="utf-8")
        return 0

    ref_bib = repo_root / "references" / "references.bib"
    doi_map: dict[str, str] = {}
    if ref_bib.exists():
        bib_content = ref_bib.read_text(encoding="utf-8", errors="ignore")
        for _, key, block in parse_bib_entries(bib_content):
            m = re.search(r"doi\s*=\s*[\"{]([^\"}]+)[\"}]", block, re.IGNORECASE)
            if m:
                d = m.group(1).strip()
                d = re.sub(r"^https?://(dx\.)?doi\.org/", "", d)
                d = re.sub(r"^doi:\s*", "", d, flags=re.IGNORECASE).strip()
                doi_map[key] = d

    def repl(match: re.Match[str]) -> str:
        keys = [k.strip() for k in match.group(2).split(",") if k.strip()]
        if mode == "dois":
            rendered = [f"DOI: {doi_map.get(k, k)}" for k in keys]
            return f"({', '.join(rendered)})"
        elif mode == "keys":
            return f"[{', '.join(keys)}]"
        return match.group(0)

    # Replace \revref{...} and \cite{...}
    text = re.sub(r"\\(cite|revref)\{([^}]+)\}", repl, text)
    dst.write_text(text, encoding="utf-8")
    return 0


def review_reference(repo_root: Path, key: str) -> int:
    """Stage one source-backed correction/exception; publish only after SAVE."""
    import tempfile

    folder = repo_root / "references"
    path = folder / "bib" / f"{key}.bib"
    if (
        path.is_symlink()
        or not path.is_file()
        or path.parent.resolve() != (folder / "bib").resolve()
    ):
        raise ValueError("Choose an existing atomic citation key")
    original = path.read_text()
    doi_path = folder / "dois.txt"
    doi_before = doi_path.read_text() if doi_path.exists() else None
    ledger_path = folder / "references.json"
    ledger_before = ledger_path.read_bytes() if ledger_path.exists() else None
    state = read_reference_state(repo_root)
    cached = {**state.get("cached_records", {}), **state.get("records", {})}.get(
        key, {}
    )
    print(original)
    correction = input(
        "Corrected publisher BibTeX file (Enter keeps current record): "
    ).strip()
    candidate = Path(correction).read_text() if correction else original
    entries = parse_bib_entries(candidate)
    if len(entries) != 1:
        raise ValueError("Correction must contain exactly one BibTeX record")
    kind, _, block = entries[0]
    fields = bib_fields(block)
    if correction:
        block = format_bib_record(kind, key, fields)
    source_url = input("Authoritative source URL: ").strip()
    parsed_url = urllib.parse.urlparse(source_url)
    if parsed_url.scheme not in {"http", "https"} or not parsed_url.netloc:
        raise ValueError("An authoritative HTTP(S) source URL is required")
    reason = input("What did you verify against that source? ").strip()
    if not reason:
        raise ValueError("A specific review reason is required")
    stamp = datetime.now(timezone.utc).isoformat()
    doi = canonical_doi(fields["doi"]) if fields.get("doi") else ""
    if doi:
        for other_path in (folder / "bib").glob("*.bib"):
            if other_path == path:
                continue
            for _, other_key, other_block in parse_bib_entries(other_path.read_text()):
                other_doi = bib_fields(other_block).get("doi", "")
                if other_doi and canonical_doi(other_doi) == canonical_doi(doi):
                    raise ValueError(
                        f"DOI already belongs to {other_key}; review identity first"
                    )
    evidence = cached.get("evidence", {})
    old_doi = cached.get("fields", {}).get("doi", "")
    digest = hashlib.sha256(block.encode()).hexdigest()
    # Source changes are not a license to silently reuse stale metadata.
    if doi and (
        not evidence.get("message")
        or canonical_doi(doi) != canonical_doi(old_doi or doi)
        or (not correction and cached.get("record_sha256") != digest)
    ):
        url = "https://api.crossref.org/works/" + urllib.parse.quote(doi, safe="")
        request = urllib.request.Request(
            url, headers={"User-Agent": "BibGen-reference-review/1.0"}
        )
        with urllib.request.urlopen(request, timeout=20) as response:
            message = json.load(response)["message"]
        evidence = {
            "source_url": url,
            "retrieved_at": stamp,
            "message": {
                name: message[name]
                for name in (
                    "DOI",
                    "title",
                    "container-title",
                    "author",
                    "volume",
                    "issue",
                    "page",
                    "article-number",
                    "published",
                    "issued",
                    "type",
                    "publisher",
                    "ISBN",
                    "ISSN",
                )
                if name in message
            },
        }
    elif not doi:
        # Explicitly attested primary metadata; never label this as registry retrieval.
        fields.setdefault("url", source_url)
        block = format_bib_record(kind, key, fields)
        digest = hashlib.sha256(block.encode()).hexdigest()
        authors = []
        for author in re.split(r"\s+and\s+", fields.get("author", "")):
            parts = author.split(",", 1)
            if len(parts) != 2:
                raise ValueError(
                    "No-DOI primary records require Family, Given author syntax"
                )
            authors.append({"family": parts[0].strip(), "given": parts[1].strip()})
        evidence = {
            "source_kind": "user-reviewed primary metadata",
            "source_url": source_url,
            "retrieved_at": stamp,
            "message": {
                "DOI": "",
                "type": {
                    "article": "journal-article",
                    "inproceedings": "proceedings-article",
                    "book": "book",
                    "inbook": "book-chapter",
                    "incollection": "book-chapter",
                }.get(kind),
                "title": [fields.get("title", "")],
                "container-title": [fields.get("journal", fields.get("booktitle", ""))],
                "published": {"date-parts": [[int(fields["year"])]]},
                "author": authors,
                **{
                    remote: fields[local]
                    for local, remote in (
                        ("volume", "volume"),
                        ("number", "issue"),
                        ("pages", "page"),
                        ("publisher", "publisher"),
                    )
                    if fields.get(local)
                },
            },
        }
    if not evidence.get("message"):
        raise ValueError(
            "Retrieve metadata with --audit-references --refresh-metadata first"
        )
    # Audit the candidate in isolation before modifying the real bibliography.
    with tempfile.TemporaryDirectory(prefix="bibgen-review-") as temporary:
        staged = Path(temporary)
        (staged / "references").mkdir()
        (staged / "references/references.bib").write_text(block)
        save_reference_state(
            staged, {"records": {key: {"record_sha256": digest, "evidence": evidence}}}
        )
        audit_references(staged, all_references=True)
        record = read_reference_state(staged)["records"][key]
    print("Proposed record:\n" + block)
    for index, flag in enumerate(record["flags"], 1):
        print(f"{index}: {flag}")
    approved = []
    if record["flags"]:
        selection = input(
            "Reviewed exception numbers, comma-separated (Enter leaves CHECK): "
        ).strip()
        if selection:
            indices = [int(value.strip()) for value in selection.split(",")]
            if any(index < 1 or index > len(record["flags"]) for index in indices):
                raise ValueError("Invalid flag selection")
            approved = [record["flags"][index - 1] for index in indices]
            if any(
                flag.startswith("missing ")
                or "mismatch" in flag
                or "unverified" in flag
                or "lookup failed" in flag
                for flag in approved
            ):
                raise ValueError(
                    "Missing fields, identity mismatches and failed verification require correction, not an exception"
                )
    print(
        f"Review source: {source_url}\nReason: {reason}\nApproved exceptions: {approved}"
    )
    if input("Type SAVE to persist; anything else cancels: ").strip() != "SAVE":
        print("Cancelled; no reference files changed")
        return 0
    if (
        path.read_text() != original
        or (ledger_path.read_bytes() if ledger_path.exists() else None) != ledger_before
    ):
        raise ValueError("Reference or review ledger changed during review; rerun")
    review = {
        "record_sha256": digest,
        "metadata_sha256": metadata_digest(evidence["message"]),
        "accepted_flags": approved,
        "reason": reason,
        "source_urls": [source_url],
        "reviewed_at": stamp,
    }
    state.setdefault("review_history", []).append(
        {
            "citekey": key,
            "previous_record": original,
            "previous_audit": cached,
            "previous_annotation": state.get("annotations", {}).get(key),
            "previous_dois": doi_before,
            "previous_review": state.get("reviews", {}).get(key),
            "review": review,
        }
    )
    state.setdefault("reviews", {})[key] = review
    state.setdefault("annotations", {})[key] = {
        "action_taken": "CLI source-backed correction/review",
        "reason": reason,
    }
    state.setdefault("records", {})[key] = record
    # Write recovery evidence before the source replacement.
    save_reference_state(repo_root, state)
    path.write_text(block + "\n")
    if doi:
        known = {line.strip().lower() for line in (doi_before or "").splitlines()}
        normalized = canonical_doi(doi)
        if normalized not in known:
            doi_path.write_text((doi_before or "").rstrip() + "\n" + normalized + "\n")
    aggregate_hub(repo_root)
    return audit_references(repo_root, all_references=True)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Bibliography Hub Aggregator & DOI Resolver",
        epilog="Normal workflow: --prepare, then inspect references/references.csv (status and comments). See scripts/README.md. Builds use no-argument offline aggregation.",
    )
    parser.add_argument(
        "--prepare",
        action="store_true",
        help="Import configured article DOIs, retrieve missing records and generate reference reports",
    )
    parser.add_argument(
        "--split",
        nargs="?",
        const="",
        help="Split references.bib (or specified file) into references/bib/ folders",
    )
    parser.add_argument(
        "--doi", type=str, help="Fetch official BibTeX for DOI from CrossRef"
    )
    parser.add_argument(
        "--dois",
        nargs="?",
        const="references/dois.txt",
        help="Explicitly fetch missing DOIs from a list (default references/dois.txt)",
    )
    parser.add_argument(
        "--all-references",
        action="store_true",
        help="Include unused library records with --audit-references",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Audit cited keys in authored documents against references.bib",
    )
    parser.add_argument(
        "--render-tex",
        choices=["numbers", "dois", "keys"],
        help="Render main.tex with resolved citations in specified mode",
    )
    parser.add_argument(
        "--audit-references",
        action="store_true",
        help="Audit cited/nocited metadata; flags require review",
    )
    parser.add_argument(
        "--refresh-metadata",
        action="store_true",
        help="Explicit Crossref network refresh with --audit-references",
    )
    parser.add_argument("--out", type=str, help="Output file path for --render-tex")

    parser.add_argument(
        "--review-reference",
        metavar="KEY",
        help="Review one atomic reference with primary evidence; preview and SAVE explicitly",
    )

    args = parser.parse_args()
    repo_root = find_repo_root()

    if args.review_reference:
        if any(
            (
                args.prepare,
                args.doi,
                args.dois is not None,
                args.check,
                args.audit_references,
                args.all_references,
                args.refresh_metadata,
                args.split is not None,
                args.render_tex,
                args.out,
            )
        ):
            parser.error("--review-reference runs alone")
        try:
            return review_reference(repo_root, args.review_reference)
        except (OSError, ValueError, KeyError, EOFError) as exc:
            print(f"Review not completed: {exc}", file=sys.stderr)
            return 1
    if args.prepare:
        if any(
            (
                args.doi,
                args.dois is not None,
                args.check,
                args.audit_references,
                args.all_references,
                args.refresh_metadata,
                args.split is not None,
                args.render_tex,
                args.out,
            )
        ):
            parser.error("--prepare runs alone")
        try:
            return prepare_references(repo_root)
        except (OSError, ValueError) as exc:
            print(f"Preparation failed: {exc}", file=sys.stderr)
            return 1
    if args.all_references and not args.audit_references:
        parser.error("--all-references requires --audit-references")
    if args.dois is not None and (
        args.doi
        or args.audit_references
        or args.check
        or args.split is not None
        or args.render_tex
    ):
        parser.error("--dois must be run separately from other actions")
    if args.refresh_metadata and not args.audit_references:
        parser.error("--refresh-metadata requires --audit-references")
    if args.audit_references:
        return audit_references(repo_root, args.refresh_metadata, args.all_references)
    if args.dois is not None:
        return ingest_doi_list(repo_root, Path(args.dois))
    if args.split is not None:
        src = Path(args.split) if args.split else None
        return split_monolith(repo_root, src)
    elif args.doi:
        return handle_doi_ingestion(repo_root, args.doi)
    elif args.check:
        return check_citations(repo_root)
    elif args.render_tex:
        out_path = Path(args.out) if args.out else None
        return render_tex_for_mode(repo_root, args.render_tex, output_file=out_path)
    else:
        # Default zero-flag action: aggregate references/bib/*.bib -> references.bib
        return aggregate_hub(repo_root)


if __name__ == "__main__":
    sys.exit(main())
