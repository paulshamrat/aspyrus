#!/usr/bin/env python3
"""bibgen.py - Bibliography Hub Aggregator & DOI Resolver for manuscript projects.

Zero-flag execution:
    python3 scripts/bibgen.py
    Collects all atomic BibTeX entries from references/bib/*.bib,
    deduplicates and alphabetizes entries, and generates canonical references/references.bib.

Advanced execution:
    python3 scripts/bibgen.py --split [file.bib]
        Atomizes a monolithic .bib file into individual references/bib/<citekey>.bib files.
    python3 scripts/bibgen.py --doi <DOI>
        Fetches official publisher BibTeX from CrossRef / doi.org and saves directly to reference folder.
    python3 scripts/bibgen.py --check
        Cross-checks references.bib against main.tex to report uncited keys and missing references.
"""

